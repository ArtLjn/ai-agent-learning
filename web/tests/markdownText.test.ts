import assert from 'node:assert/strict'
import test from 'node:test'

import { normalizeMarkdownText } from '../src/lib/markdownText.ts'

test('将行内编号和星号条目整理为可渲染 Markdown 列表', () => {
  const source = [
    '您好，欢迎加入云舟科技。关于您咨询的新员工入职流程、资源发放及制度查看事宜，根据现有资料为您梳理如下：',
    '1. 当前状态核实与所需信息 由于系统尚未显示您的邮箱、办公电脑已发放，且无法直接定位到您的具体权限配置，为了协助您快速推进后续流程，请补充提供以下关键信息以便进一步核查：',
    '* 员工号（您提供的2098） * 姓名 * 所属部门 * 入职日期 * 办公地点',
    '2. 新人入职常规办理内容 新员工入职通常涉及以下核心事项，请您在等待资源到位期间留意：',
    '* 账号与通讯工具：包括公司邮箱、钉钉账号的开通。 * 办公设备：办公电脑的领取、安装及调试。',
  ].join(' ')

  const normalized = normalizeMarkdownText(source)

  assert.match(normalized, /如下：\n\n### 1\. 当前状态核实与所需信息\n\n由于系统尚未显示/)
  assert.match(normalized, /核查：\n\n- 员工号（您提供的2098）\n- 姓名\n- 所属部门\n- 入职日期\n- 办公地点/)
  assert.match(normalized, /办公地点\n\n### 2\. 新人入职常规办理内容\n\n新员工入职通常/)
  assert.match(normalized, /留意：\n\n- 账号与通讯工具：包括公司邮箱、钉钉账号的开通。\n- 办公设备：办公电脑的领取、安装及调试。/)
})

test('将截图中的报销处理结果整理为小标题和项目符号', () => {
  const source = '您好，关于您咨询的报销制度及入口指引，根据现有资料为您梳理如下： 1. 提交入口指引 云舟服务台是公司内部员工问题的统一受理入口。您可以选择以下任一渠道进行问题提交或业务操作： * 钉钉“小舟助手” * 云舟员工门户 * 服务台 Web 页面 针对具体的财务报销业务（如提交报销单、查看付款状态、上传发票和附件），通常涉及财务报销系统；若部分费用需先提交事前申请或预算审批，则可能涉及钉钉审批流程。建议您优先通过上述统一入口进入相关功能模块进行操作。 2. 报销材料要求及流程提示 目前资料中未详细列出所有具体报销材料的清单细节，但明确了报销前的关键合规要求： * 事前审批确认：在发起报销前，请务必先确认该笔费用是否需要事前审批。 * 发票处理：可使用电子发票平台查验发票真伪，避免重复报销，并确保抬头和税号正确。 * 预算核对：建议提前在预算系统中查看成本中心、项目编号及预算占用情况，以确保报销顺利。 3. 需要补充的信息 由于知识库资料未包含具体的“报销材料详细清单”以及“事前审批的具体触发条件”，若您有特定类型的费用（如差旅、招待等）需要报销，可能需要进一步提供费用类型信息，以便获取更精准的材料要求指引。'

  const normalized = normalizeMarkdownText(source)

  assert.match(normalized, /如下：\n\n### 1\. 提交入口指引\n\n云舟服务台/)
  assert.match(normalized, /操作：\n\n- 钉钉“小舟助手”\n- 云舟员工门户\n- 服务台 Web 页面\n\n针对具体的财务报销业务/)
  assert.match(normalized, /操作。\n\n### 2\. 报销材料要求及流程提示\n\n目前资料中/)
  assert.match(normalized, /关键合规要求：\n\n- 事前审批确认：/)
  assert.match(normalized, /顺利。\n\n### 3\. 需要补充的信息\n\n由于知识库资料/)
})
